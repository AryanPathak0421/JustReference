#!/usr/bin/env node
/**
 * Creates apps/api/.env for local development with freshly generated secrets and a dev Super Admin.
 * Does nothing if .env already exists. Never use these values in production.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(dir, '.env');
if (existsSync(target)) {
  console.log('apps/api/.env already exists — left unchanged.');
  process.exit(0);
}

const values = {
  JWT_ACCESS_SECRET: randomBytes(48).toString('base64url'),
  FIELD_ENCRYPTION_KEY: randomBytes(32).toString('base64'),
  SEED_SUPERADMIN_NAME: 'Dev Super Admin',
  SEED_SUPERADMIN_EMAIL: 'superadmin@example.test',
  SEED_SUPERADMIN_MOBILE: '9000000001',
  SEED_SUPERADMIN_PASSWORD: `Dev-${randomBytes(9).toString('base64url')}`,
  SEED_DEMO_MEMBER_PASSWORD: `Demo-${randomBytes(9).toString('base64url')}`,
  SEED_DEMO_ADMIN_PASSWORD: `Demo-${randomBytes(9).toString('base64url')}`,
  SEED_DEMO_VENDOR_PASSWORD: `Demo-${randomBytes(9).toString('base64url')}`,
};

let text = readFileSync(join(dir, '.env.example'), 'utf8');
for (const [k, v] of Object.entries(values)) text = text.replace(new RegExp(`^${k}=.*$`, 'm'), `${k}=${v}`);
writeFileSync(target, `# Generated by scripts/init-env.mjs for LOCAL DEVELOPMENT ONLY.\n${text}`);
console.log('Created apps/api/.env (dev Super Admin login is in SEED_SUPERADMIN_EMAIL / SEED_SUPERADMIN_PASSWORD).');
